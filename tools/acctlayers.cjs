const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const b=await chromium.launch({executablePath:process.env.ACCT_CHROME,ignoreDefaultArgs:['--hide-scrollbars']});
 let fail=0,passed=0;
 const check=(label,ok)=>{console.log((ok?'PASS ':'FAIL ')+label);ok?passed++:fail++};
 const p=await b.newPage({viewport:{width:390,height:844},reducedMotion:'no-preference'});
 // Reproduce the deployed Liquid shell rather than assuming the static hook.
 const theme=fs.readFileSync(path.join(__dirname,'../../Gumi-Brand-shopify/baseline-20260930-a50/sections/gb-account.liquid'),'utf8');
 const shellTag=theme.match(/<div class="gb-acct__views"[^>]*>/)[0];
 await p.route('**/account.html',route=>route.fulfill({contentType:'text/html',body:fs.readFileSync(path.join(__dirname,'../account.html'),'utf8').replace('<div class="gb-acct__views" data-acct-views>',shellTag)}));
 await p.goto(pathToFileURL(path.join(__dirname,'../account.html')).href);await p.waitForTimeout(600);
 check('deployed shell participates in view transitions',await p.locator('.gb-acct__views').evaluate(e=>e.hasAttribute('data-acct-views')));
 await p.evaluate(()=>{document.querySelector('[data-acct-view="overview"]').style.minHeight='2500px'});
 await p.locator('.gb-acct-list [data-acct-goto="subscriptions"]').click();
 await p.waitForTimeout(150);
 const mid=await p.evaluate(()=>{const a=document.querySelector('[data-acct-view="overview"]'),b=document.querySelector('[data-acct-view="subscriptions"]'),s=document.querySelector('.gb-acct__views');return {old:a.getBoundingClientRect().height,incoming:b.getBoundingClientRect().height,shell:s.getBoundingClientRect().height,transform:getComputedStyle(a).transform,inert:a.inert}});
 check('old overview retains its full height mid-cover',mid.old>=2499);
 check('incoming cover spans all old content',mid.incoming>=2499);
 check('shell does not collapse during cover',mid.shell>=2499);
 check('old overview remains stationary',mid.transform==='none');
 check('old overview cannot take focus during cover',mid.inert);
 await p.waitForTimeout(1100);
 check('mobile hidden views use opacity/visibility without display:none',await p.locator('[data-acct-view="overview"]').evaluate(e=>getComputedStyle(e).display!=='none'&&getComputedStyle(e).opacity==='0'&&getComputedStyle(e).visibility==='hidden'));
 check('temporary shell sizing is cleared',await p.locator('.gb-acct__views').evaluate(e=>!e.style.height));
 check('only current view remains interactive',await p.locator('[data-acct-view]').evaluateAll(es=>es.filter(e=>!e.inert).length===1));
 await p.evaluate(()=>window.gumiAcct.view.show('overview',false));
 await p.evaluate(()=>window.gumiAcct.view.show('subscriptions',true));
 await p.waitForTimeout(650);
 const settling=await p.locator('.gb-acct__views').evaluate(e=>({height:e.getBoundingClientRect().height,running:e.getAnimations().some(a=>a.playState==='running')}));
 check('shorter view height settles smoothly after covering',settling.height<2500&&settling.running);
 await p.setViewportSize({width:1440,height:900});
 check('resize clears temporary cover styles',await p.locator('.gb-acct__views').evaluate(e=>!e.style.height&&!e.querySelector('.is-covering')));
 check('desktop inactive views keep display:none',await p.locator('[data-acct-view="overview"]').evaluate(e=>getComputedStyle(e).display==='none'));
 const base=fs.readFileSync(path.join(__dirname,'../../Gumi-Brand-shopify/baseline-20260930-a49/assets/base.css'),'utf8');
 await p.evaluate(css=>{const s=document.createElement('style');s.textContent=css;document.head.prepend(s)},base);
 await p.evaluate(()=>window.gumiAcct.modal.open('shipping-current'));await p.waitForTimeout(450);await p.mouse.move(0,0);
 const radio=p.locator('.gb-acct-addr__radio:checked').first();
 const r=await radio.evaluate(e=>({ring:getComputedStyle(e).borderTopColor,ringStyle:getComputedStyle(e).borderTopStyle,dot:getComputedStyle(e).backgroundImage}));
 check('checked address radio has ink ring',r.ring==='rgb(1, 19, 7)'&&r.ringStyle==='solid');
 check('checked address dot is green before hover',r.dot.includes('rgb(0, 86, 53)'));
 await radio.hover();check('checked address hover keeps ink ring',await radio.evaluate(e=>getComputedStyle(e).borderTopColor)==='rgb(1, 19, 7)');
 await p.evaluate(()=>window.gumiAcct.modal.open('shipping-form'));await p.waitForTimeout(450);
 const scroll=await p.locator('[data-acct-modal-panel="shipping-form"] .gb-acct-modal__body').evaluate(e=>({thumb:getComputedStyle(e,'::-webkit-scrollbar-thumb').backgroundColor,width:getComputedStyle(e,'::-webkit-scrollbar').width,radius:getComputedStyle(e,'::-webkit-scrollbar-thumb').borderRadius}));
 check('scrollbar thumb matches Figma gray',scroll.thumb==='rgb(230, 230, 230)');
 check('scrollbar has 16px lane and 8px radius',scroll.width==='16px'&&scroll.radius==='8px');
 for(const height of [600,700]) {
  const q=await b.newPage({viewport:{width:1440,height}});
  await q.goto(pathToFileURL(path.join(__dirname,'../account.html')).href+'#detail');await q.waitForTimeout(600);
  await q.evaluate(()=>window.gumiAcct.modal.open('edit-date'));await q.waitForTimeout(700);
  const measure=()=>q.locator('.gb-acct-modal.is-open .gb-acct-field__input').evaluate(e=>{const r=e.getBoundingClientRect(),s=e.closest('.gb-acct-modal__body');return {left:r.left,right:r.right,scrollbar:s.offsetWidth-s.clientWidth}});
  const before=await measure();
  await q.locator('.gb-acct-modal.is-open .gb-acct-field__input').click();await q.waitForTimeout(900);
  const after=await measure();
  check(`${height}: calendar actually creates a scrollbar`,after.scrollbar>0);
  check(`${height}: styled scrollbar preserves calendar field position`,Math.abs(after.left-before.left)<0.5&&Math.abs(after.right-before.right)<0.5);
  await q.close();
 }
 await b.close();console.log(`${passed} passed / ${fail} failed`);process.exitCode=fail?1:0;
})().catch(e=>{console.error(e);process.exit(1)});
